const I18N_STORAGE_KEY='tw_language';let currentLanguage=localStorage.getItem(I18N_STORAGE_KEY)==='zh'?'zh':'en';
function i18nFormat(key,vars={}){const table=I18N_MESSAGES[currentLanguage]||I18N_MESSAGES.en;let value=table[key]??I18N_MESSAGES.en[key]??key;for(const [name,replacement] of Object.entries(vars))value=value.replaceAll('{'+name+'}',String(replacement));return value}
const I18N_ENGLISH_KEYS=Object.fromEntries(Object.entries(I18N_MESSAGES.en).map(([key,value])=>[value,key]));
function i18nText(value){const source=String(value??'');const key=I18N_ENGLISH_KEYS[source];return key?i18nFormat(key):source}
function i18nHTML(html){if(currentLanguage==='en')return html;const template=document.createElement('template');template.innerHTML=String(html??'');i18nApply(template.content);return template.innerHTML}
function i18nApply(root=document){document.documentElement.lang=currentLanguage;document.title=i18nFormat('page.title');root.querySelectorAll?.('[data-i18n]').forEach(el=>{if(!el.closest('[data-i18n-skip]'))el.textContent=i18nFormat(el.dataset.i18n)});const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);for(const node of nodes){if(node.parentElement?.closest('[data-i18n-skip]'))continue;const raw=node.nodeValue,trimmed=raw.trim(),key=I18N_ENGLISH_KEYS[trimmed];if(key)node.nodeValue=raw.replace(trimmed,i18nFormat(key))}root.querySelectorAll?.('[title]').forEach(el=>{if(!el.closest('[data-i18n-skip]'))el.title=i18nText(el.title)});const button=document.getElementById('languageButton');if(button)button.textContent=i18nFormat('language.switch')}
function i18nMessage(message){const source=String(message??'');if(currentLanguage==='en')return source;const failed=source.indexOf(' failed: ');if(failed>0)return i18nFormat('result.failed',{action:i18nText(source.slice(0,failed)),error:i18nText(source.slice(failed+9))});if(source.endsWith(' ok'))return i18nFormat('result.ok',{action:i18nText(source.slice(0,-3))});if(source.endsWith(' started'))return i18nFormat('result.started',{action:i18nText(source.slice(0,-8))});return i18nText(source)}
